export function wildlifeForMonth(month: number): WildlifeSpecies[] {
  return wildlifeSpecies.filter((s) => s.season.monthsPossible.includes(month))
}

export function wildlifeForRegion(regionId: string): WildlifeSpecies[] {
  return wildlifeSpecies.filter((s) => s.bestRegionIds.includes(regionId))
}

export function wildlifeByCategory(category: WildlifeSpecies['category']): WildlifeSpecies[] {
  return wildlifeSpecies.filter((s) => s.category === category)
}
